/**
 * The blank template (blueprint section 17): a workbook with a sheet for each kind of record an upload takes, the headers in place,
 * a dropdown on every column that takes one of a few values, and an example row or two marked EXAMPLE that the reader ignores.
 *
 * It is the shape of the export, so a person can fill it in offline, or export the household, change rows and bring the file back.
 * The About sheet carries the template version and the instructions. Nothing about any household is in it.
 */

import { TEMPLATE_VERSION } from './entities.ts';
import { buildWorkbook, type SheetModel } from './workbook.ts';
import type { Cell } from './cells.ts';

const EXAMPLE = 'EXAMPLE: delete this row';

const INSTRUCTIONS: readonly (readonly [string, string])[] = [
  ['What this is', 'A blank workbook for the Family Finance Buddy upload. Fill it in, then use Upload on the Reports screen: you see what it would do before anything is written.'],
  ['Sheets', 'A sheet for each kind of record. You can leave any sheet empty and delete the ones you do not use.'],
  ['New rows', 'Leave id empty. Write the member, category, holding or property by its name in the column beside the empty id (member_name, category_name, holding_name).'],
  ['Names', 'A name has to match one record, exactly as the app shows it. If two records have the same name, write the id instead.'],
  ['Ref', 'Give every new row a ref of your own (BB-17, kitchen loan). If you upload the corrected file again, the ref is how the app knows the row is the one it added the first time, so it is updated and not added twice.'],
  ['Examples', 'Rows whose ref begins with EXAMPLE only show the shape. They are ignored: delete them or leave them.'],
  ['Amounts', 'In rupees (or the currency of the row), the way you would write them: 1,23,456.50 works. Put the currency in the currency column.'],
  ['Dates', 'Write a date as YYYY-MM-DD (2026-10-31).'],
  ['Choices', 'A column with a fixed list of choices has a dropdown. Only those values are accepted.'],
  ['Deleting', 'An upload never deletes. A row you leave out is left alone. To retire a record, set its status.'],
  ['Undo', 'An upload can be reversed as a whole from the Reports screen, by the person who made it.'],
];

/** One example row for a sheet: the cells named by header, every other cell empty. */
function example(sheet: SheetModel, cells: Readonly<Record<string, Cell>>): readonly Cell[] {
  return sheet.headers.map((header) => (header === 'ref' ? EXAMPLE : (cells[header] ?? null)));
}

const EXAMPLES: Readonly<Record<string, Readonly<Record<string, Cell>>[]>> = {
  Categories: [{ name: 'Car insurance', nature: 'fixed', is_essential: true, status: 'active' }],
  Expenses: [
    { member_name: 'A member as shown in the app', category_name: 'A category as shown in the app', txn_date: '2026-10-31', amount: 642.5, currency: 'INR', payee: 'Swiggy', method: 'upi', visibility: 'household' },
  ],
  Holdings: [
    { member_name: 'A member as shown in the app', name: 'A fund or share', kind: 'mutual_fund', currency: 'INR', exposure_currency: 'INR', is_foreign_asset: false, quantity: 100, cost: 250000, visibility: 'household', status: 'active' },
  ],
  Liabilities: [{ name: 'Home loan', kind: 'home_loan', instalment: 42000, currency: 'INR', cadence: 'monthly', status: 'active' }],
};

/** The template's sheets, ready to be written as a file. */
export function buildTemplate(exportedAt: string): { readonly sheets: readonly SheetModel[] } {
  const { workbook } = buildWorkbook({}, { exportedAt, householdName: 'Blank template', baseCurrency: 'INR', demo: false });
  const sheets: SheetModel[] = [];
  for (const sheet of workbook.sheets) {
    if (sheet.entity === null) {
      sheets.push({
        ...sheet,
        rows: [['Template version', TEMPLATE_VERSION], ['Generated by', 'Family Finance Buddy'], ['Generated at', exportedAt], ...INSTRUCTIONS.map(([item, text]) => [item, text] as const)],
      });
      continue;
    }
    if (sheet.readOnly) continue;
    const examples = EXAMPLES[sheet.name] ?? [];
    sheets.push({ ...sheet, rows: examples.map((cells) => example(sheet, cells)) });
  }
  return { sheets };
}
