/**
 * Family Finance Buddy — the proposed departures, grouped by area, for one sitting.
 *
 * `docs/design/conformance.md` keeps a Departures table: where the app and the design differ on purpose. A row the owner has not ruled on is `proposed`; there were 166 on
 * 23 November 2026. This reads that table and writes `docs/drafts/departures-review.md`: each proposed row once, under the area it belongs to, with what it is and why, so the owner
 * can rule on them area by area. It decides nothing and changes no row. The grouping is by what the row is about, from its title, and a row that fits no area is listed under Other so
 * that none is lost: the count at the top is checked against the table.
 *
 * Run: node scripts/departures-review.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'docs/design/conformance.md';
const OUTPUT = 'docs/drafts/departures-review.md';

/** The areas, in the order they are listed, with the words in a row's title that put it there. The first that matches wins. */
const AREAS = [
  ['Card cycles', /^card cycles/i],
  ['Import (statements, files, uploads, exports)', /(import|upload|statement(?!-date)|export|template|report|workbook|backup)/i],
  ['Theme, layout and the design system', /(linen|mist|theme|dark|colour|token|layout|panel|boxes|soft|flat|tab\b|tabs|board|artboard|icon|glyph|font|type|header|bar\b|menu|shell|desktop|phone|responsive|spacing|radius|chip|pill|segmented)/i],
  ['Ledger, money and the month close', /(money|ledger|account|credit|transfer|close|month|spent|saved|income|balance|stated|reserve|salary|rule|expected|loan payment|cover)/i],
  ['Holdings, property, insurance and planning', /(holding|gold|property|insurance|policy|deposit|bond|ppf|fund|equity|nps|goal|earmark|fire|plan|tax|asset|allocation|overview|summary|net worth|profile|settings|more\b)/i],
];

const text = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');
const lines = text.split('\n');
const start = lines.findIndex((line) => line.startsWith('| What | The prototype | The app | Why | Status |'));
if (start < 0) throw new Error(`The Departures table was not found in ${SOURCE}.`);

const rows = [];
for (const line of lines.slice(start + 2)) {
  if (!line.startsWith('|')) break;
  const cells = line.slice(1, line.lastIndexOf('|')).split(/\s\|\s/).map((cell) => cell.trim());
  if (cells.length < 3) continue;
  rows.push({ title: cells[0] ?? '', why: cells[cells.length - 2] ?? '', status: (cells[cells.length - 1] ?? '').toLowerCase() });
}

const proposed = rows.filter((row) => row.status === 'proposed');
const byArea = new Map(AREAS.map(([name]) => [name, []]));
byArea.set('Other', []);
for (const row of proposed) {
  const found = AREAS.find(([, pattern]) => pattern.test(row.title));
  byArea.get(found === undefined ? 'Other' : found[0]).push(row);
}

const clip = (value, length) => (value.length <= length ? value : `${value.slice(0, length).replace(/\s+\S*$/, '')}…`);
const out = [
  '# Proposed departures, by area',
  '',
  `Generated by \`node scripts/departures-review.mjs\` from the Departures table of \`${SOURCE}\`: **${String(proposed.length)} rows are \`proposed\`** (of ${String(rows.length)} in all). Each is listed once, under the area its title is about, so they can be ruled on area by area. Ruling on one means changing its Status in \`${SOURCE}\` to \`decided\` (or reversing the departure, which is a change to the app). This file decides nothing.`,
  '',
];
for (const [name, list] of byArea) {
  if (list.length === 0) continue;
  out.push(`## ${name} (${String(list.length)})`, '', '| What | Why |', '|---|---|');
  for (const row of list) out.push(`| ${row.title.replace(/\|/g, '/')} | ${clip(row.why, 260).replace(/\|/g, '/')} |`);
  out.push('');
}
const total = [...byArea.values()].reduce((sum, list) => sum + list.length, 0);
if (total !== proposed.length) throw new Error('A proposed row was lost in the grouping.');
writeFileSync(OUTPUT, `${out.join('\n')}\n`);
console.log(`  ${String(proposed.length)} proposed departures written to ${OUTPUT}: ${[...byArea].map(([name, list]) => `${name} ${String(list.length)}`).join(', ')}.`);
